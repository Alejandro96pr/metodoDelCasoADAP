-- TURBINE: modelo fisico inicial, primera parte del diagrama de clases.
-- Oracle SQL. Para visualizar sin crear tablas: Data Modeler > File > Import > DDL File.
-- No incluye facturacion, pagos ni control (segunda parte).

CREATE TABLE ROL (
  id_rol NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR2(30) NOT NULL,
  CONSTRAINT pk_rol PRIMARY KEY (id_rol),
  CONSTRAINT uq_rol_nombre UNIQUE (nombre)
);

CREATE TABLE USUARIO (
  id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_rol NUMBER NOT NULL,
  correo_corporativo VARCHAR2(254) NOT NULL,
  hash_clave VARCHAR2(255) NOT NULL,
  estado VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
  intentos_fallidos NUMBER(3) DEFAULT 0 NOT NULL,
  CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
  CONSTRAINT uq_usuario_correo UNIQUE (correo_corporativo),
  CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol) REFERENCES ROL(id_rol),
  CONSTRAINT ck_usuario_estado CHECK (estado IN ('ACTIVO','BLOQUEADO','INACTIVO')),
  CONSTRAINT ck_usuario_intentos CHECK (intentos_fallidos >= 0)
);

CREATE TABLE TOKEN_RECUPERACION (
  id_token NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_usuario NUMBER NOT NULL,
  hash_token VARCHAR2(255) NOT NULL,
  caduca_en TIMESTAMP NOT NULL,
  usado_en TIMESTAMP,
  CONSTRAINT pk_token PRIMARY KEY (id_token),
  CONSTRAINT uq_token_hash UNIQUE (hash_token),
  CONSTRAINT fk_token_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIO(id_usuario)
);

CREATE TABLE EMPRESA_CLIENTE (
  id_empresa NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nif VARCHAR2(30) NOT NULL,
  razon_social VARCHAR2(200) NOT NULL,
  estado VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
  direccion VARCHAR2(300),
  pais VARCHAR2(100),
  sector VARCHAR2(100),
  CONSTRAINT pk_empresa PRIMARY KEY (id_empresa),
  CONSTRAINT uq_empresa_nif UNIQUE (nif),
  CONSTRAINT ck_empresa_estado CHECK (estado IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE CONTACTO (
  id_contacto NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_empresa NUMBER NOT NULL,
  nombre VARCHAR2(150) NOT NULL,
  correo VARCHAR2(254),
  telefono VARCHAR2(30),
  activo CHAR(1) DEFAULT 'S' NOT NULL,
  CONSTRAINT pk_contacto PRIMARY KEY (id_contacto),
  CONSTRAINT fk_contacto_empresa FOREIGN KEY (id_empresa) REFERENCES EMPRESA_CLIENTE(id_empresa),
  CONSTRAINT ck_contacto_activo CHECK (activo IN ('S','N'))
);

CREATE TABLE ASIGNACION_CLIENTE (
  id_asignacion NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_usuario NUMBER NOT NULL,
  id_empresa NUMBER NOT NULL,
  tipo VARCHAR2(20) NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE,
  CONSTRAINT pk_asignacion PRIMARY KEY (id_asignacion),
  CONSTRAINT fk_asig_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIO(id_usuario),
  CONSTRAINT fk_asig_empresa FOREIGN KEY (id_empresa) REFERENCES EMPRESA_CLIENTE(id_empresa),
  CONSTRAINT ck_asig_tipo CHECK (tipo IN ('TITULAR','COLABORADOR')),
  CONSTRAINT ck_asig_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- Solo un titular vigente por empresa.
CREATE UNIQUE INDEX uq_asig_titular_vigente ON ASIGNACION_CLIENTE
(CASE WHEN tipo = 'TITULAR' AND fecha_fin IS NULL THEN id_empresa END);

CREATE TABLE TAREA_CLIENTE (
  id_tarea NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_empresa NUMBER NOT NULL,
  descripcion VARCHAR2(1000) NOT NULL,
  estado VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
  responsable NUMBER,
  vence_en DATE,
  CONSTRAINT pk_tarea PRIMARY KEY (id_tarea),
  CONSTRAINT fk_tarea_empresa FOREIGN KEY (id_empresa) REFERENCES EMPRESA_CLIENTE(id_empresa),
  CONSTRAINT fk_tarea_responsable FOREIGN KEY (responsable) REFERENCES USUARIO(id_usuario),
  CONSTRAINT ck_tarea_estado CHECK (estado IN ('PENDIENTE','EN_CURSO','COMPLETADA','CANCELADA'))
);

CREATE TABLE HISTORIAL_ASIGNACION_TAREA (
  id_historial NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_tarea NUMBER NOT NULL,
  id_usuario NUMBER NOT NULL,
  fecha_inicio TIMESTAMP NOT NULL,
  fecha_fin TIMESTAMP,
  CONSTRAINT pk_hist_asig_tarea PRIMARY KEY (id_historial),
  CONSTRAINT fk_hist_tarea FOREIGN KEY (id_tarea) REFERENCES TAREA_CLIENTE(id_tarea),
  CONSTRAINT fk_hist_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIO(id_usuario),
  CONSTRAINT ck_hist_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE TABLE PLAN (
  id_plan NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR2(100) NOT NULL,
  descripcion VARCHAR2(500),
  activo CHAR(1) DEFAULT 'S' NOT NULL,
  CONSTRAINT pk_plan PRIMARY KEY (id_plan),
  CONSTRAINT uq_plan_nombre UNIQUE (nombre),
  CONSTRAINT ck_plan_activo CHECK (activo IN ('S','N'))
);

CREATE TABLE VERSION_TARIFA (
  id_version NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_plan NUMBER NOT NULL,
  tramo_anual_min NUMBER(12,2) NOT NULL,
  tramo_anual_max NUMBER(12,2) NOT NULL,
  cuota_mensual NUMBER(12,2) NOT NULL,
  version_tabla NUMBER(6),
  vigencia_desde DATE,
  vigencia_hasta DATE,
  CONSTRAINT pk_version_tarifa PRIMARY KEY (id_version),
  CONSTRAINT fk_version_plan FOREIGN KEY (id_plan) REFERENCES PLAN(id_plan),
  CONSTRAINT ck_version_tramo CHECK (tramo_anual_max >= tramo_anual_min),
  CONSTRAINT ck_version_cuota CHECK (cuota_mensual >= 0),
  CONSTRAINT ck_version_fechas CHECK (vigencia_hasta IS NULL OR vigencia_desde IS NULL OR vigencia_hasta >= vigencia_desde)
);

CREATE TABLE SUSCRIPCION (
  id_suscripcion NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_empresa NUMBER NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_baja_efectiva DATE,
  estado VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
  condiciones_pago VARCHAR2(500),
  CONSTRAINT pk_suscripcion PRIMARY KEY (id_suscripcion),
  CONSTRAINT fk_suscripcion_empresa FOREIGN KEY (id_empresa) REFERENCES EMPRESA_CLIENTE(id_empresa),
  CONSTRAINT ck_suscripcion_estado CHECK (estado IN ('PENDIENTE','ACTIVA','CANCELADA')),
  CONSTRAINT ck_suscripcion_baja CHECK (fecha_baja_efectiva IS NULL OR fecha_baja_efectiva >= fecha_inicio)
);

-- Solo una suscripcion activa por empresa.
CREATE UNIQUE INDEX uq_suscripcion_activa_empresa ON SUSCRIPCION
(CASE WHEN estado = 'ACTIVA' THEN id_empresa END);

CREATE TABLE REVISION_ANUAL (
  id_revision NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_empresa NUMBER NOT NULL,
  importe_anual NUMBER(14,2) NOT NULL,
  fuente VARCHAR2(200) NOT NULL,
  fecha_revision DATE NOT NULL,
  fecha_datos DATE,
  CONSTRAINT pk_revision PRIMARY KEY (id_revision),
  CONSTRAINT fk_revision_empresa FOREIGN KEY (id_empresa) REFERENCES EMPRESA_CLIENTE(id_empresa),
  CONSTRAINT ck_revision_importe CHECK (importe_anual >= 0)
);

-- Una revision por empresa y año natural (indice basado en funcion).
CREATE UNIQUE INDEX uq_revision_empresa_anio ON REVISION_ANUAL
(id_empresa, EXTRACT(YEAR FROM fecha_revision));

CREATE TABLE PROPUESTA_TARIFA (
  id_propuesta NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_suscripcion NUMBER NOT NULL,
  id_version NUMBER NOT NULL,
  id_revision NUMBER,
  resuelta_por NUMBER,
  importe_propuesto NUMBER(12,2) NOT NULL,
  fecha_efecto DATE NOT NULL,
  tipo VARCHAR2(30),
  estado VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
  comentario VARCHAR2(1000),
  CONSTRAINT pk_propuesta PRIMARY KEY (id_propuesta),
  CONSTRAINT fk_prop_suscripcion FOREIGN KEY (id_suscripcion) REFERENCES SUSCRIPCION(id_suscripcion),
  CONSTRAINT fk_prop_version FOREIGN KEY (id_version) REFERENCES VERSION_TARIFA(id_version),
  CONSTRAINT fk_prop_revision FOREIGN KEY (id_revision) REFERENCES REVISION_ANUAL(id_revision),
  CONSTRAINT fk_prop_usuario FOREIGN KEY (resuelta_por) REFERENCES USUARIO(id_usuario),
  CONSTRAINT uq_prop_revision UNIQUE (id_revision),
  CONSTRAINT ck_prop_importe CHECK (importe_propuesto >= 0),
  CONSTRAINT ck_prop_estado CHECK (estado IN ('PENDIENTE','APROBADA','RECHAZADA'))
);

-- Una sola propuesta pendiente por suscripcion.
CREATE UNIQUE INDEX uq_propuesta_pendiente_suscripcion ON PROPUESTA_TARIFA
(CASE WHEN estado = 'PENDIENTE' THEN id_suscripcion END);

CREATE TABLE VIGENCIA_TARIFA (
  id_vigencia NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_suscripcion NUMBER NOT NULL,
  id_version NUMBER NOT NULL,
  id_propuesta NUMBER,
  importe_mensual NUMBER(12,2) NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE,
  CONSTRAINT pk_vigencia PRIMARY KEY (id_vigencia),
  CONSTRAINT fk_vig_suscripcion FOREIGN KEY (id_suscripcion) REFERENCES SUSCRIPCION(id_suscripcion),
  CONSTRAINT fk_vig_version FOREIGN KEY (id_version) REFERENCES VERSION_TARIFA(id_version),
  CONSTRAINT fk_vig_propuesta FOREIGN KEY (id_propuesta) REFERENCES PROPUESTA_TARIFA(id_propuesta),
  CONSTRAINT uq_vig_propuesta UNIQUE (id_propuesta),
  CONSTRAINT ck_vig_importe CHECK (importe_mensual >= 0),
  CONSTRAINT ck_vig_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
